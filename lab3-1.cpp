 // 1. Ввести n (1..10) — число зон посадки. 
 // С помощью for вывести номер зоны и время начала посадки, если первая начинается в 10:00,
 // а каждая следующая на 10 минут позже. Достаточно вывести количество минут после 10:00.//

#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "Russian"); 

    int n;
    cout << "Введите число зон посадки (1..10): ";
    cin >> n;

    
    if (n < 1 || n > 10) {
        cout << "Ошибка: число должно быть от 1 до 10." << endl;
        return 1;
    }

    
    for (int i = 1; i <= n; i++) {
        
        int minutesAfter10 = (i - 1) * 10;

        cout << "Зона " << i << ": " << minutesAfter10 << " минут после 10:00" << endl;
    }

    return 0;
}